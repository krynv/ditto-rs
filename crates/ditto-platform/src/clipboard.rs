//! Reading, writing and watching the system clipboard.

use std::sync::mpsc;
use std::thread::JoinHandle;

use clipboard_rs::{
    Clipboard, ClipboardContent, ClipboardContext, ClipboardHandler, ClipboardWatcher, ClipboardWatcherContext,
    ContentFormat, RustImageData, WatcherShutdown,
};
use clipboard_rs::common::RustImage;
use ditto_core::model::{ClipContent, formats};
use ditto_core::settings::Settings;
use ditto_core::text::strip_cf_html_header;

use crate::{PlatformError, Result};

/// Extra format added to everything Ditto-RS puts on the clipboard so that its own watcher
/// can ignore the change (Ditto adds its private ignore format for the same reason).
pub const SELF_MARKER: &str = "org.dittors.self";

/// Formats that password managers and other tools set to say "do not record this".
pub const PRIVACY_MARKERS: &[&str] = &[
    // macOS conventions, see http://nspasteboard.org
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "Pasteboard generator type",
    // Windows: honoured by Ditto itself and by the Windows clipboard history
    "Clipboard Viewer Ignore",
    "ExcludeClipboardContentFromMonitorProcessing",
    // KDE / KeePassXC on Linux
    "x-kde-passwordManagerHint",
];

fn err(e: impl std::fmt::Display) -> PlatformError {
    PlatformError::Clipboard(e.to_string())
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ReadOptions {
    pub text: bool,
    pub html: bool,
    pub rtf: bool,
    pub images: bool,
    pub files: bool,
    /// 0 = unlimited.
    pub max_bytes: u64,
    pub respect_privacy_markers: bool,
    /// Also read what Ditto-RS itself put on the clipboard (normally reported as `OwnWrite`).
    pub include_own_writes: bool,
}

impl Default for ReadOptions {
    fn default() -> Self {
        Self {
            text: true,
            html: true,
            rtf: true,
            images: true,
            files: true,
            max_bytes: 0,
            respect_privacy_markers: true,
            include_own_writes: false,
        }
    }
}

impl ReadOptions {
    pub fn from_settings(s: &Settings) -> Self {
        Self {
            text: s.capture.text,
            html: s.capture.html,
            rtf: s.capture.rtf,
            images: s.capture.images,
            files: s.capture.files,
            max_bytes: s.max_clip_bytes,
            respect_privacy_markers: s.respect_privacy_markers,
            include_own_writes: false,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ReadOutcome {
    Content(ClipContent),
    /// Put there by Ditto-RS itself.
    OwnWrite,
    /// Marked as secret/transient by the app that copied it.
    Concealed,
    /// Larger than `max_bytes`.
    TooLarge(u64),
    /// Nothing in a format we capture.
    Empty,
}

fn too_large(opts: &ReadOptions, size: usize) -> bool {
    opts.max_bytes > 0 && size as u64 > opts.max_bytes
}

/// Read the current clipboard into a [`ClipContent`].
pub fn read(opts: &ReadOptions) -> Result<ReadOutcome> {
    let ctx = ClipboardContext::new().map_err(err)?;
    let available = ctx.available_formats().unwrap_or_default();
    if !opts.include_own_writes && available.iter().any(|f| f == SELF_MARKER) {
        return Ok(ReadOutcome::OwnWrite);
    }
    if opts.respect_privacy_markers && is_concealed(&ctx, &available) {
        return Ok(ReadOutcome::Concealed);
    }

    let mut content = ClipContent::new();
    if opts.files && ctx.has(ContentFormat::Files) {
        if let Ok(files) = ctx.get_files() {
            let files: Vec<String> = files.iter().filter_map(|f| normalize_file_entry(f)).collect();
            content.set_files(&files);
        }
    }
    if opts.text && ctx.has(ContentFormat::Text) {
        if let Ok(text) = ctx.get_text() {
            if too_large(opts, text.len()) {
                return Ok(ReadOutcome::TooLarge(text.len() as u64));
            }
            if !text.is_empty() {
                content.set(formats::TEXT, text.into_bytes());
            }
        }
    }
    if opts.html && ctx.has(ContentFormat::Html) {
        if let Ok(html) = ctx.get_html() {
            let html = strip_cf_html_header(&html);
            if !html.trim().is_empty() {
                content.set(formats::HTML, html.as_bytes().to_vec());
            }
        }
    }
    if opts.rtf && ctx.has(ContentFormat::Rtf) {
        if let Ok(rtf) = ctx.get_rich_text() {
            if !rtf.trim().is_empty() {
                content.set(formats::RTF, rtf.into_bytes());
            }
        }
    }
    // Copying files also puts their icons on the clipboard; those are not worth keeping.
    if opts.images && !content.has(formats::FILES) && ctx.has(ContentFormat::Image) {
        match ctx.get_image() {
            Ok(img) => {
                let (w, h) = img.get_size();
                if too_large(opts, w as usize * h as usize * 4) {
                    return Ok(ReadOutcome::TooLarge(u64::from(w) * u64::from(h) * 4));
                }
                match img.to_png() {
                    Ok(png) => content.set(formats::PNG, png.get_bytes().to_vec()),
                    Err(e) => log::warn!("could not encode clipboard image: {e}"),
                }
            }
            Err(e) => log::debug!("no readable image on the clipboard: {e}"),
        }
    }

    let size = content.total_size();
    if too_large(opts, size) {
        return Ok(ReadOutcome::TooLarge(size as u64));
    }
    Ok(if content.is_empty() { ReadOutcome::Empty } else { ReadOutcome::Content(content) })
}

fn is_concealed(ctx: &ClipboardContext, available: &[String]) -> bool {
    if available.iter().any(|f| PRIVACY_MARKERS.contains(&f.as_str())) {
        return true;
    }
    // Windows: a DWORD 0 in "CanIncludeInClipboardHistory" opts out of clipboard history.
    if available.iter().any(|f| f == "CanIncludeInClipboardHistory") {
        if let Ok(buf) = ctx.get_buffer("CanIncludeInClipboardHistory") {
            return buf.len() >= 4 && buf[..4] == [0, 0, 0, 0];
        }
    }
    false
}

/// Turn a clipboard file entry (path or `file://` URI) into a local path.
pub fn normalize_file_entry(entry: &str) -> Option<String> {
    let entry = entry.trim();
    if entry.is_empty() || entry.starts_with('#') {
        return None;
    }
    if let Some(rest) = entry.strip_prefix("file://") {
        let rest = rest.strip_prefix("localhost").unwrap_or(rest);
        let decoded = percent_decode(rest);
        // file:///C:/dir → C:/dir on Windows
        #[cfg(windows)]
        let decoded = decoded.strip_prefix('/').filter(|p| p.chars().nth(1) == Some(':')).map(str::to_string).unwrap_or(decoded);
        return Some(decoded);
    }
    Some(entry.to_string())
}

fn percent_decode(s: &str) -> String {
    fn hex(b: u8) -> Option<u8> {
        (b as char).to_digit(16).map(|d| d as u8)
    }
    let bytes = s.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%' && i + 2 < bytes.len() {
            if let (Some(hi), Some(lo)) = (hex(bytes[i + 1]), hex(bytes[i + 2])) {
                out.push(hi << 4 | lo);
                i += 3;
                continue;
            }
        }
        out.push(bytes[i]);
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// Put a clip on the clipboard with every format it has.
pub fn write(content: &ClipContent) -> Result<()> {
    let mut items = Vec::new();
    if let Some(t) = content.text() {
        items.push(ClipboardContent::Text(t.to_string()));
    }
    if let Some(h) = content.html() {
        items.push(ClipboardContent::Html(h.to_string()));
    }
    if let Some(r) = content.rtf() {
        items.push(ClipboardContent::Rtf(r.to_string()));
    }
    if let Some(png) = content.png() {
        match RustImageData::from_bytes(png) {
            Ok(img) => items.push(ClipboardContent::Image(img)),
            Err(e) => log::warn!("could not decode stored image: {e}"),
        }
    }
    let files = content.files();
    if !files.is_empty() {
        items.push(ClipboardContent::Files(files));
    }
    if items.is_empty() {
        return Err(PlatformError::Clipboard("the clip has no format that can be put on the clipboard".into()));
    }
    items.push(ClipboardContent::Other(SELF_MARKER.into(), b"1".to_vec()));
    let ctx = ClipboardContext::new().map_err(err)?;
    ctx.set(items).map_err(err)
}

/// Keeps the watcher thread alive; dropping it stops watching.
pub struct Watcher {
    shutdown: Option<WatcherShutdown>,
    _thread: JoinHandle<()>,
}

impl Drop for Watcher {
    fn drop(&mut self) {
        // WatcherShutdown signals the watch loop to stop when dropped.
        self.shutdown.take();
    }
}

struct Handler<F>(F);

impl<F: FnMut()> ClipboardHandler for Handler<F> {
    fn on_clipboard_change(&mut self) {
        (self.0)();
    }
}

/// Call `on_change` (on a background thread) whenever the clipboard changes.
pub fn watch<F: FnMut() + Send + 'static>(on_change: F) -> Result<Watcher> {
    let (tx, rx) = mpsc::channel::<Result<WatcherShutdown>>();
    let thread = std::thread::Builder::new()
        .name("clipboard-watcher".into())
        .spawn(move || {
            // Create the context on the thread that runs the loop (Windows needs its
            // message window and the loop on the same thread).
            #[cfg(target_os = "macos")]
            let ctx = ClipboardWatcherContext::<Handler<F>>::new_with_interval(std::time::Duration::from_millis(250));
            #[cfg(not(target_os = "macos"))]
            let ctx = ClipboardWatcherContext::<Handler<F>>::new();
            let mut ctx = match ctx {
                Ok(c) => c,
                Err(e) => {
                    let _ = tx.send(Err(err(e)));
                    return;
                }
            };
            ctx.add_handler(Handler(on_change));
            let _ = tx.send(Ok(ctx.get_shutdown_channel()));
            ctx.start_watch();
        })
        .map_err(err)?;
    let shutdown = rx.recv().map_err(|_| PlatformError::Clipboard("clipboard watcher thread died".into()))??;
    Ok(Watcher { shutdown: Some(shutdown), _thread: thread })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn file_entries() {
        assert_eq!(normalize_file_entry("/tmp/a b.txt").as_deref(), Some("/tmp/a b.txt"));
        assert_eq!(normalize_file_entry("file:///tmp/a%20b.txt").as_deref(), Some("/tmp/a b.txt"));
        assert_eq!(normalize_file_entry("file://localhost/tmp/x").as_deref(), Some("/tmp/x"));
        assert_eq!(normalize_file_entry("# comment"), None);
        assert_eq!(normalize_file_entry("  "), None);
        assert_eq!(percent_decode("%E2%9C%93 ok %zz %4"), "✓ ok %zz %4");
    }
}
